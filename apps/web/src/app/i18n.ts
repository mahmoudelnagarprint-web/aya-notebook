export function createTranslator(dictionaries: Record<Language, MessageDict>, language: Language) {
  return (key: string, values?: Record<string, string | number>): string => {
    const template = dictionaries[language][key] ?? dictionaries.en[key] ?? commonMessages[language][key] ?? key;
    return formatMessage(template, values);
  };
}
